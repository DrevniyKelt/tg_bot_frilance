def _repair_ru_mojibake(value: str) -> str:
    if not isinstance(value, str):
        return value
    if "Р" not in value and "С" not in value and "В" not in value:
        return value
    try:
        repaired = value.encode("cp1251").decode("utf-8")
    except UnicodeError:
        return value
    return repaired or value

